package com.practika.hospitalclicker

import kotlin.random.Random

/** Бегущая строка: забавные больничные новости, зависящие от состояния игры. */
object News {

    private val general = listOf(
        "Учёные доказали: улыбка врача лечит лучше витаминов",
        "Бабушка заняла очередь к терапевту в 5 утра — «чтобы без очереди»",
        "Медсёстры требуют больше кофе. Главврач обещал подумать",
        "В буфете больницы закончились пирожки. Пациенты в панике",
        "Опрос: 9 из 10 пациентов довольны. Десятый просто спал",
        "Голубь залетел в регистратуру и получил медкарту",
        "Интерн перепутал градусник с ручкой. Подписи стали горячими",
        "Главврача заметили с тремя стетоскопами одновременно",
        "Пациент выздоровел, едва увидев счёт за лечение",
        "Больничный кот официально назначен заведующим отделением уюта",
        "Аптека больницы ввела скидку на витамин C для всех, кто улыбнулся",
        "Врачи советуют: мойте руки, спите и не забывайте нажимать на больницу",
        "Учёные выяснили, что яблоко в день не заменяет главврача",
        "В регистратуре наконец-то нашли ручку, которая пишет",
    )

    fun next(game: Game): String {
        val pool = ArrayList<String>(general)

        game.event?.let { e ->
            val line = if (e.type.kind == EventKind.OUTBREAK) {
                "⚠️ СРОЧНО: ${e.type.title}! Горожан просят мыть руки и не паниковать"
            } else {
                "${e.type.emoji} ${e.type.title}: главврач доволен, персонал ликует"
            }
            // Новость о событии — самая важная
            repeat(4) { pool += line }
        }

        pool += "Местная газета: «${game.rank.title}» — лучшая в округе"

        fun has(id: String, n: Int = 1) = (game.doctors.firstOrNull { it.id == id }?.count ?: 0) >= n
        if (has("nurse", 10)) pool += "Медсёстры больницы организовали хор и поют пациентам колыбельные"
        if (has("pediatrician")) pool += "Педиатр раздал рекордные 500 леденцов за смелость"
        if (has("dentist")) pool += "Стоматолог уверяет, что ни один пациент не плакал. Почти"
        if (has("surgeon")) pool += "Хирург провёл операцию за рекордные 4 минуты и успел на обед"
        if (has("ambulance", 5)) pool += "Скорая приезжает так быстро, что пациенты не успевают заболеть"
        if (has("psychotherapist")) pool += "Психотерапевт выслушал главврача. Главврач тоже доволен"
        if (has("geneticist")) pool += "Генетики вывели помидор, который сам измеряет давление"
        if (has("nanosurgeon")) pool += "Нанороботы просят прибавку: «Мы маленькие, но гордые»"
        if (has("spacedoctor")) pool += "Космический врач принимает на орбите: очередь на ракету расписана на год"

        when (game.mapId) {
            "city" -> pool += "Горожане выбирают вашу клинику: «Близко к метро и хорошие врачи»"
            "mountains" -> pool += "Санаторий: горный воздух и лыжи вместо таблеток"
            "island" -> pool += "Пациенты отказываются выписываться с тропического острова"
            "megapolis" -> pool += "Пробки мешают скорой — фельдшеры пересели на самокаты"
            "mars" -> pool += "На Марсе открыта первая палата с видом на Землю"
        }

        if (game.stars > 0) pool += "Звёзд репутации у больницы уже ${game.stars} — конкуренты нервничают"
        if (game.lifetimeEarned > 1e12) pool += "Больница заработала больше, чем бюджет небольшой страны"
        if (game.outbreaksCured >= 10) pool += "ВОЗ вручила главврачу медаль за борьбу с эпидемиями"
        if (game.unlockedAchievements.size >= 20) pool += "Стену больницы уже не видно за грамотами и кубками"

        return "📰  " + pool[Random.nextInt(pool.size)]
    }
}
